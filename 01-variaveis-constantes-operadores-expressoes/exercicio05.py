# Peça ao usuário dois números inteiros utilizando input(), convertendo-os
# com a função int(). Exiba a soma, a subtração, a multiplicação e a
# divisão entre eles.

a = int(input('Digite o primeiro número: '))
b = int(input('Digite o segundo número: '))

print(a + b)
print(a - b)
print(a * b)
print(a / b)