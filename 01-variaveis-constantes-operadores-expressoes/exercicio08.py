# Exercício 08
# Peça ao usuário dois números utilizando input(). Utilize operadores
# relacionais (>, <, ==, >=, <=, !=) para comparar os dois valores e exiba
# o resultado de cada comparação.

a = int(input('Digite o primeiro número: '))
b = int(input('Digite o segundo número: '))

print(a > b)
print(a >= b)
print(a < b)
print(a <= b)
print(a == b)
print(a != b)